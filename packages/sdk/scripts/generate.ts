import { writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { LocalCredentialStore } from '@cuttingfloor/credentials';
import * as schema from '@cuttingfloor/schema';
import { EDIT_TOOLS } from '@cuttingfloor/schema';
import { createServer, Runtime } from '@cuttingfloor/server';
import { McpServer } from '@modelcontextprotocol/server';
import * as z from 'zod/v4';

// Writes src/tools.generated.ts from the tool registry: every registered tool's name, and its
// input and result types from the same Zod schemas the server validates with. A test fails when
// the file is stale; regenerate with `node packages/sdk/scripts/generate.ts`.

export const GENERATED = new URL('../src/tools.generated.ts', import.meta.url);

/** Results of tools registered without an output schema (long-running ones as their job ends). */
const RESULTS: Record<string, string> = {
  'edit.batch': 'BatchResult',
  'audio.set_loudness': 'EditResult',
  'media.import': 'MediaInfo',
  'media.analyze': 'MediaInfo',
  'create.motion': 'MediaInfo',
  'create.still': 'MediaInfo',
  'create.matte': 'MediaInfo',
  'create.voiceover': 'MediaInfo',
  'create.cutout': 'MediaInfo',
  'export.video': 'ExportResult',
  'export.timeline': 'ExportTimelineResult',
  'code.run': 'CodeRunResult',
};

export async function generateTools(): Promise<string> {
  // One name per schema; where a schema has several (TimelineGetResult = TimelineView), the
  // tool-shaped one, so the output is the same whatever order the exports come in.
  const names = new Map<unknown, string>();
  const rank = (n: string) => `${/(Input|Result)$/.test(n) ? 0 : 1}${n}`;
  for (const [name, value] of Object.entries(schema)) {
    if (!(value instanceof z.ZodType)) continue;
    const had = names.get(value);
    if (!had || rank(name) < rank(had)) names.set(value, name);
  }
  const seen: Array<{ name: string; input: unknown; output: unknown }> = [];
  const register = McpServer.prototype.registerTool;
  McpServer.prototype.registerTool = function (
    this: McpServer,
    name: string,
    config: never,
    cb: never,
  ) {
    const c = config as { inputSchema?: unknown; outputSchema?: unknown };
    seen.push({ name, input: c.inputSchema, output: c.outputSchema });
    return register.call(this, name, config, cb);
  } as typeof register;
  try {
    const dir = join(tmpdir(), `cf-sdk-gen-${process.pid}`);
    const runtime = new Runtime({
      dataDir: dir,
      mode: 'local',
      publicUrl: 'http://127.0.0.1',
      mediaRoots: [],
      exportsDir: null,
      maxJobs: 1,
      outputUrlTtlMs: 1,
      maxDownloadBytes: 1,
      allowPrivateUrls: false,
      inlineMaxBytes: 1,
      motionUrl: null,
    });
    createServer({ runtime, credentials: new LocalCredentialStore({}, false), owner: () => 'x' });
  } finally {
    McpServer.prototype.registerTool = register;
  }
  const edit = new Set<string>(EDIT_TOOLS);
  const used = new Set<string>();
  const type = (s: string) => {
    used.add(s);
    return s;
  };
  const tools = seen.sort((a, b) => a.name.localeCompare(b.name));
  const inputs = tools.map(({ name, input }) => {
    const known = names.get(input);
    const t = known
      ? `z.input<typeof ${type(known)}>`
      : edit.has(name)
        ? `z.input<ReturnType<typeof ${type('editInput')}<'${name}'>>>`
        : 'Record<string, unknown>';
    return `  '${name}': ${t};`;
  });
  const outputs = tools.map(({ name, output }) => {
    const known = names.get(output) ?? RESULTS[name] ?? (edit.has(name) ? 'EditResult' : undefined);
    return `  '${name}': ${known ? `z.output<typeof ${type(known)}>` : 'Record<string, unknown>'};`;
  });
  return `// Generated by packages/sdk/scripts/generate.ts from the tool registry. Don't edit.
import type {
${[...used]
  .sort()
  .map((u) => `  ${u},`)
  .join('\n')}
} from '@cuttingfloor/schema';
import type * as z from 'zod/v4';

export type ToolName =
${tools.map((t) => `  | '${t.name}'`).join('\n')};

export interface ToolInputs {
${inputs.join('\n')}
}

export interface ToolOutputs {
${outputs.join('\n')}
}

export const TOOL_NAMES: readonly ToolName[] = [
${tools.map((t) => `  '${t.name}',`).join('\n')}
];
`;
}

if (import.meta.main) {
  await writeFile(GENERATED, await generateTools());
  process.stdout.write(`wrote ${GENERATED.pathname}\n`);
}
