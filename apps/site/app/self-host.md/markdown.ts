import {
  IMAGE,
  KEYS,
  LICENCE,
  LOCAL_ADDRESS,
  NO_KEY,
  REPO_URL,
  SELF_HOST_STEPS,
} from '../../content/facts.ts';
import { cell } from '../lib/markdown.ts';
import {
  AGPL,
  COMPARE,
  CONTRIBUTING_URL,
  LICENCE_URL,
  LOCAL_CONNECT,
  LOCAL_NOTES,
  REQUIREMENTS,
  SELF_HOST_DESCRIPTION,
  SELF_HOST_LEAD,
  SELF_HOST_TITLE,
  UPDATE_STEPS,
} from '../self-host/copy.ts';
import { SITE_URL } from '../seo.ts';

// /self-host in plain Markdown, built from the same data as the page.

export function markdown(): string {
  const body = [
    `# ${SELF_HOST_TITLE}`,
    '',
    `> ${SELF_HOST_DESCRIPTION}`,
    '',
    'Download it, make it your own, or go hosted.',
    '',
    SELF_HOST_LEAD,
    '',
    `- Source: ${REPO_URL}`,
    `- Image: ${IMAGE}`,
    `- Licence: ${LICENCE} (${LICENCE_URL})`,
    `- Hosted instead: ${SITE_URL}/connect`,
    `- Web page: ${SITE_URL}/self-host`,
    '',
    '## Quick start',
    '',
    '```sh',
    ...SELF_HOST_STEPS,
    '```',
    '',
    `Then point your agent at ${LOCAL_ADDRESS}.`,
    '',
    '## Connect your agent',
    '',
    ...LOCAL_NOTES.map((n) => `- ${n}`),
    '',
    ...LOCAL_CONNECT.flatMap((s) => [`${s.label}:`, '', '```', s.code, '```', '']),
    '## Hosted or yourself',
    '',
    'Same code. Nothing is held back when you run it yourself; paying for hosted buys one thing: we run it.',
    '',
    '| | Hosted (cuttingfloor.ai) | Run it yourself |',
    '|---|---|---|',
    ...COMPARE.map((r) => `| ${cell(r.row)} | ${cell(r.hosted)} | ${cell(r.self)} |`),
    '',
    '## Keys',
    '',
    '| Feature | Hosted | Run it yourself |',
    '|---|---|---|',
    ...KEYS.map((k) => `| ${cell(k.feature)} | ${cell(k.hosted)} | ${cell(k.selfHosted)} |`),
    '',
    'Built in, no key, either way:',
    '',
    ...NO_KEY.map((n) => `- ${n}`),
    '',
    'Running it yourself, keys go in the .env file next to compose.yaml. Run `docker compose up -d` after adding one.',
    '',
    `## What ${LICENCE} means for you`,
    '',
    ...AGPL.map((a) => `- **${a.q}.** ${a.a}`),
    '',
    '## What you need',
    '',
    ...REQUIREMENTS.map((r) => `- ${r}`),
    '',
    `To update later: \`${UPDATE_STEPS.join(' && ')}\``,
    '',
    '## Make it your own',
    '',
    `The code, issues and releases are on GitHub: ${REPO_URL}. To send a change, read CONTRIBUTING.md (${CONTRIBUTING_URL}): fork it, branch from develop and open a pull request.`,
    '',
  ].join('\n');
  return body;
}
